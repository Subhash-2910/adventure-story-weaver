"""Measure the trained GPT against a bigram baseline and record sample outputs.

Writes results/metrics.json and results/samples.md. All numbers are on the held-out validation
split (the last 10% of the corpus tokens, never trained on).
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import torch

from app.baseline import BigramBaseline
from app.corpus import load_corpus
from app.embeddings import encode_corpus
from app.generate import SamplingConfig, StoryGenerator
from app.train import split_data

PROMPTS = [
    "The cave mouth was black, and from somewhere deep inside it came",
    "Captain Hawk unrolled the old map on the table and pointed at",
    "When the sun rose over the desert, we saw",
    '"We cannot stay here," said the guide. "',
    "I drew my sword and stepped towards the strange green warrior,",
]


@torch.no_grad()
def full_val_loss(model, ids: torch.Tensor, block: int) -> float:
    """Exact loss over the whole validation split, in non-overlapping windows."""
    total, count = 0.0, 0
    for start in range(0, len(ids) - 1, block):
        x = ids[start:start + block]
        y = ids[start + 1:start + block + 1]
        x = x[:len(y)]
        if len(x) == 0:
            break
        _, loss = model(x[None], y[None])
        total += loss.item() * len(y)
        count += len(y)
    return total / count


def copied_fraction(text: str, corpus_ngrams: set, n: int = 8) -> float:
    """Share of the sample's n-word sequences that appear word-for-word in the corpus."""
    words = text.split()
    grams = [" ".join(words[i:i + n]) for i in range(len(words) - n + 1)]
    return sum(g in corpus_ngrams for g in grams) / len(grams) if grams else 0.0


def evaluate(checkpoints: str | Path, out: str | Path, seed: int = 7) -> dict:
    gen = StoryGenerator(checkpoints)
    tok, model = gen.tokenizer, gen.model
    text = load_corpus(Path(__file__).resolve().parent.parent / "data" / "corpus.txt")
    ids = encode_corpus(tok, text)
    train_ids, val_ids = split_data(ids, 0.1)

    gpt_loss = full_val_loss(model, val_ids, model.cfg.block_size)
    bigram = BigramBaseline(tok.vocab_size).fit(train_ids)
    big_loss = bigram.loss(val_ids)
    uniform = math.log(tok.vocab_size)

    words = text.split()
    corpus_ngrams = {" ".join(words[i:i + 8]) for i in range(len(words) - 7)}

    samples, md = [], ["# Sample outputs\n", f"Generated by `python -m app.cli evaluate` (seed {seed}). "
                       "The **bold** part is the prompt; the rest is the model.\n"]
    for temp in (0.5, 0.8, 1.1):
        md.append(f"\n## Temperature {temp}\n")
        for i, prompt in enumerate(PROMPTS):
            cfg = SamplingConfig(max_new_tokens=80, temperature=temp, seed=seed + i)
            cont = gen.continue_story(prompt, cfg)
            copied = copied_fraction(prompt + cont, corpus_ngrams)
            samples.append({"temperature": temp, "prompt": prompt, "continuation": cont,
                            "copied_8gram_fraction": round(copied, 3)})
            md.append(f"- **{prompt}**{cont}\n")
    md.append("\n## Bigram baseline (temperature 0.8), for comparison\n")
    for i, prompt in enumerate(PROMPTS[:3]):
        p_ids = tok.encode(prompt)
        out_ids = bigram.generate(p_ids, 60, temperature=0.8, seed=seed + i)
        md.append(f"- **{prompt}**{tok.decode(out_ids[len(p_ids):])}\n")

    report = {
        "validation_tokens": len(val_ids),
        "gpt": {"val_loss": round(gpt_loss, 4), "perplexity": round(math.exp(gpt_loss), 1),
                "params": model.num_params(), "trained_steps": gen.meta.get("step")},
        "bigram_baseline": {"val_loss": round(big_loss, 4), "perplexity": round(math.exp(big_loss), 1)},
        "uniform_guess": {"val_loss": round(uniform, 4), "perplexity": tok.vocab_size},
        "gpt_vs_bigram_perplexity_reduction": f"{100 * (1 - math.exp(gpt_loss - big_loss)):.0f}%",
        "mean_copied_8gram_fraction": round(sum(s["copied_8gram_fraction"] for s in samples) / len(samples), 3),
        "samples": samples,
    }
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2))
    plot_loss(Path(checkpoints) / "train_log.json", out.parent / "loss_curve.png", big_loss)
    (out.parent / "samples.md").write_text("\n".join(md))
    return report


def plot_loss(log_path: Path, png_path: Path, bigram_loss: float | None = None) -> bool:
    """Train/validation loss curve from train_log.json (skipped if matplotlib is not installed)."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return False
    if not log_path.exists():
        return False
    hist = json.loads(log_path.read_text())["history"]
    steps = [h["step"] for h in hist]
    fig, ax = plt.subplots(figsize=(7, 4), dpi=120)
    ax.plot(steps, [h["train_loss"] for h in hist], label="train", color="#2a6fdb")
    ax.plot(steps, [h["val_loss"] for h in hist], label="validation", color="#e07b00")
    if bigram_loss is not None:
        ax.axhline(bigram_loss, ls="--", color="#888", label=f"bigram baseline ({bigram_loss:.2f})")
    ax.set_xlabel("training step")
    ax.set_ylabel("cross-entropy loss (nats/token)")
    ax.set_ylim(top=min(8.5, max(h["val_loss"] for h in hist) + 0.2))
    ax.set_title("Adventure Story Weaver GPT (7.2M params)")
    ax.grid(alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(png_path)
    plt.close(fig)
    return True
